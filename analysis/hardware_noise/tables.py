"""SI table: per-readout agreement of the Aquila features with the statevector emulation.

Pearson and Spearman correlation, RMSE and MAE across the observables of each sample, as median and
interquartile range over samples, per readout time and observable type; signal retention a(T) with its
bootstrap CI; the matched-count shot emulation as the shot-noise reference. Read from the CSVs written by
analysis.py (agreement_per_sample.csv, retention.csv); no recomputation. booktabs, caption above, as the
other LaTeX tables (analysis/tables/). Writes results/hardware_noise/tables/tab_si_noise_agreement.tex.

    python analysis/hardware_noise/tables.py
"""
import pandas as pd

from common import OUT, READOUT_TIMES

TAB = OUT / "tables"
BLOCKS = [("detuning", "CARDS_2500", "Detuning encoding, CARDS\\_2500 (2,571 samples)"),
          ("position", "CARDS_1000", "Position encoding, CARDS\\_1000 (1,000 samples)")]
OBS = [("Z", "$\\langle Z_i\\rangle$"), ("ZZ", "$\\langle Z_iZ_j\\rangle$")]
METRICS = [("pearson", "Pearson $r$"), ("spearman", "Spearman $\\rho$"), ("rmse", "RMSE"), ("mae", "MAE")]
NCOLS = 2 + len(READOUT_TIMES)


def cell(m, lo, hi):
    return f"{m:.2f} [{lo:.2f}, {hi:.2f}]".replace("-", "$-$")


def series(df, **sel):
    g = df
    for k, v in sel.items():
        g = g[g[k] == v]
    g = g.sort_values("readout_us")
    assert list(g.readout_us) == list(READOUT_TIMES), sel
    return g


def agreement_row(a, enc, sub, x, obs, metric, label, metric_label):
    g = series(a, encoding=enc, subset=sub, x=x, y="hw", obs=obs, metric=metric)
    return f"{label} & {metric_label} & " + " & ".join(cell(r["median"], r.q25, r.q75) for _, r in g.iterrows()) + "\\\\"


def main():
    a = pd.read_csv(OUT / "agreement_per_sample.csv")
    ret = pd.read_csv(OUT / "retention.csv")
    rows = []
    for b, (enc, sub, title) in enumerate(BLOCKS):
        n = series(a, encoding=enc, subset=sub, x="aquila", y="hw", obs="Z", metric="pearson").n.unique()
        assert len(n) == 1 and n[0] == {"CARDS_2500": 2571, "CARDS_1000": 1000}[sub], (enc, n)
        if b:
            rows.append("\\addlinespace")
        rows.append(f"\\multicolumn{{{NCOLS}}}{{@{{}}l}}{{\\textbf{{{title}}}}}\\\\")
        rows.append(f"\\multicolumn{{{NCOLS}}}{{@{{}}l}}{{\\textit{{Aquila}} vs statevector emulation}}\\\\")
        for obs, olab in OBS:
            for i, (metric, mlab) in enumerate(METRICS):
                rows.append(agreement_row(a, enc, sub, "aquila", obs, metric, olab if i == 0 else "", mlab))
        g = series(ret, encoding=enc, subset=sub, x="aquila", y="hw", obs="all")
        rows.append("All & retention $a(T)$ & " +
                    " & ".join(cell(r.slope, r.ci_lo, r.ci_hi) for _, r in g.iterrows()) + "\\\\")
        rows.append(f"\\multicolumn{{{NCOLS}}}{{@{{}}l}}{{Shot emulation vs statevector emulation "
                    f"(shot-noise reference)}}\\\\")
        for obs, olab in OBS:
            for i, (metric, mlab) in enumerate(METRICS[:1] + METRICS[2:3]):
                rows.append(agreement_row(a, enc, sub, "shot", obs, metric, olab if i == 0 else "", mlab))
        s = series(ret, encoding=enc, subset=sub, x="shot", y="hw", obs="all").slope
        assert (s - 1).abs().max() < 0.02, (enc, s.tolist())

    header = "Observable & Metric & " + " & ".join(f"{t:g}\\,$\\mu$s" for t in READOUT_TIMES) + "\\\\"
    caption = ("Agreement of the hardware features with the statevector emulation of the same programs, per readout "
               "time $T$ and observable type. Pearson and Spearman correlation, RMSE and MAE are computed for each "
               "sample across its observables (detuning: 12 $\\langle Z_i\\rangle$ and 66 $\\langle Z_iZ_j\\rangle$; "
               "position: 13 and 78) and reported as median [interquartile range] over samples. The signal retention "
               "$a(T)$ is the slope of the centred \\textit{Aquila} features on the centred emulated features, pooled "
               "over all observables, with a 95\\,\\% bootstrap interval over samples [in brackets]. The shot emulation "
               "draws, for each sample and readout, as many records from the emulated state as \\textit{Aquila} kept "
               "after post-selection; it gives $a(T) = 1.00 \\pm 0.01$ at every readout, so shot noise does not bias "
               "$a(T)$.")
    lines = ["% generated by analysis/hardware_noise/tables.py -- do not edit by hand",
             "\\begin{table}[htbp]", "\\centering", f"\\caption{{{caption}}}", "\\label{tab:si-noise-agreement}",
             "\\scriptsize", "\\setlength{\\tabcolsep}{4pt}",
             f"\\begin{{tabular}}{{@{{}}ll{'c' * len(READOUT_TIMES)}@{{}}}}", "\\toprule", header, "\\midrule",
             *rows, "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / "tab_si_noise_agreement.tex").write_text("\n".join(lines) + "\n")
    print("wrote", TAB / "tab_si_noise_agreement.tex")


if __name__ == "__main__":
    main()
