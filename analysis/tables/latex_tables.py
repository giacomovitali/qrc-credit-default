def check_resamplers(manifests):
    seen = {}
    for path, m in manifests.items():
        for res, d in m.get("resamplers", {}).items():
            fixed = {k: v for k, v in d.items() if k not in ("time_s", "n_before", "n_after", "random_state")}
            if res == "CC":
                fixed["estimator"] = re.sub(r"n_clusters=[^,]+, random_state=\d+", "n_clusters=<minority>, random_state=<seed>", fixed["estimator"])
            if res == "kSMOTE":
                fixed["kmeans_estimator"] = re.sub(r"random_state=\d+", "random_state=<seed>", fixed["kmeans_estimator"])
            if d["random_state"] != m["args"]["resample_seed"]:
                raise SystemExit(f"{path}: resampler random_state {d['random_state']} != resample seed")
            seen.setdefault(res, set()).add(json.dumps(fixed, sort_keys=True))
    if any(len(v) != 1 for v in seen.values()):
        raise SystemExit(f"resampler settings differ between runs: {seen}")
    return {k: json.loads(next(iter(v))) for k, v in seen.items()}


