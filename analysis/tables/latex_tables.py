def check_reservoir():
    cfg = {p.stem: tomllib.loads(p.read_text()) for p in (ROOT / "configs" / "reservoir").glob("*.toml")}
    for name, c in cfg.items():
        L = c["layer"]
        assert (L["t_start"], L["t_end"], L["step"], L["scale"]) == (0.0, 2.5, 0.5, 10.0), name
        assert abs(L["omega"] - 2 * np.pi) < 1e-12, name
        if c["encoding"] == "detuning":
            assert abs(L["delta"] - (4.5 + np.pi)) < 1e-12 and L["delta_max"] == -9.0, name
        else:
            assert L["delta"] == 2.0 and L["lambda"] == 1.0, name
        if c["backend"] == "hardware":
            assert c["seed"] == 1234 and 240 in c["shot_counts"], name
    used = set()
    for p in glob.glob(str(REV / "emulation" / "*_hw.manifest.json")):
        m = json.loads(Path(p).read_text())
        used.add((m["config"]["encoding"], m["config"]["backend"], m["git_commit"][:7], m["git_dirty"], m["julia_version"]))
    return cfg, used


