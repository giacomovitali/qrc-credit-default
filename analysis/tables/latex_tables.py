def num(v):
    if v is None:
        return "--"
    if isinstance(v, str):
        return {"sqrt": "$\\sqrt{d}$"}.get(v, v)
    return f"{v:g}"


def fmt_params(model, p):
    p = json.loads(p) if isinstance(p, str) else p
    if model == "KNN":
        return f"$k={p['n']}$"
    if model == "SGD":
        return f"{p['n']} epochs"
    if model in ("LM", "LSVM"):
        return f"$C={num(p['C'])}$"
    if model == "P":
        return f"$\\eta_0={num(p['learning_rate'])}$"
    if model in ("NBT", "NB"):
        return "--"
    if model == "DNN":
        return f"lr {num(p['learning_rate'])}, batch {p['batch_size']}"
    if model == "DTR":
        return ", ".join([f"depth {p['max_depth']}"] * (p["max_depth"] is not None) + [f"leaf {p['min_samples_leaf']}"])
    if model in ("RFR", "ET"):
        return ", ".join([f"feat.\\ {num(p['max_features'])}", f"leaf {p['min_samples_leaf']}"]
                         + [f"depth {p['max_depth']}"] * (p["max_depth"] is not None))
    if model == "HGB":
        return f"lr {num(p['learning_rate'])}, {p['max_leaf_nodes']} leaves, {p['max_iter']} it."
    raise ValueError(model)


