def check_grids(runs):
    bad = []
    for m, g in runs.groupby("model"):
        grid = GRIDS[m]
        if set(g.grid_size.astype(int)) != {len(grid)}:
            bad.append(f"{m}: logged grid sizes {sorted(set(g.grid_size))} != {len(grid)}")
        keys = {json.dumps(p, sort_keys=True) for p in grid}
        seen = {json.dumps(json.loads(p) or {}, sort_keys=True) for p in g.best_params}
        if not seen <= keys:
            bad.append(f"{m}: selected values outside the grid: {sorted(seen - keys)[:3]}")
    if bad:
        raise SystemExit("grid check failed:\n" + "\n".join(bad))
    return {m: len(GRIDS[m]) for m in sorted(set(runs.model))}


