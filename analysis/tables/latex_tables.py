def read(path, **kw):
    return pd.read_csv(path, keep_default_na=False, dtype={"dataset": str}, float_precision="round_trip", **kw)


def pm(m, s, d=3):
    m, s = pd.to_numeric(m, errors="coerce"), pd.to_numeric(s, errors="coerce")
    if pd.isna(m):
        return "--"
    return f"{m:.{d}f}" if pd.isna(s) else f"{m:.{d}f}\\,$\\pm$\\,{s:.{d}f}"


def tex(s):
    """Unicode labels of the study scripts -> LaTeX."""
    return (s.replace("\u2009", " ").replace("⟨Z⟩", "$\\langle Z\\rangle$").replace(" µs", "\\,$\\mu$s").replace("µs", "$\\mu$s")
            .replace("Aquila", AQ).replace(" x ", " $\\times$ ").replace("-", "--").replace("_", "\\_"))


def write(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(body.rstrip() + "\n")
    print("wrote", (OUT / name).relative_to(ROOT))


def table(label, caption, colspec, header, rows, size="\\small", notes=None):
    lines = [f"% generated by analysis/tables/latex_tables.py -- do not edit by hand",
             "\\begin{table}[htbp]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}", size,
             f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header, "\\midrule", *rows, "\\bottomrule",
             "\\end{tabular}"]
    if notes:
        lines += ["", f"\\parbox{{\\linewidth}}{{\\footnotesize {notes}}}"]
    return "\n".join(lines + ["\\end{table}"])


def longtable(label, caption, colspec, header, rows, ncols, size="\\scriptsize"):
    return "\n".join([
        "% generated by analysis/tables/latex_tables.py -- do not edit by hand",
        "\\begingroup", size, "\\setlength{\\tabcolsep}{3pt}",
        f"\\begin{{longtable}}{{{colspec}}}", f"\\caption{{{caption}}}\\label{{{label}}}\\\\",
        "\\toprule", header, "\\midrule", "\\endfirsthead",
        f"\\multicolumn{{{ncols}}}{{@{{}}l}}{{\\tablename~\\thetable{{}} (continued)}}\\\\", "\\toprule", header,
        "\\midrule", "\\endhead", "\\midrule", f"\\multicolumn{{{ncols}}}{{r@{{}}}}{{continued on the next page}}\\\\",
        "\\endfoot", "\\bottomrule", "\\endlastfoot", *rows, "\\end{longtable}", "\\endgroup"])


def group_row(text, ncols, first=False):
    return ([] if first else ["\\addlinespace"]) + [f"\\multicolumn{{{ncols}}}{{@{{}}l}}{{\\textbf{{{text}}}}}\\\\"]


